/* global self, fetch, Headers, Response, URL */
// GitHub Pages can't set response headers, so this service worker adds the two that make the page
// cross-origin isolated: that lets speech recognition use several CPU threads (SharedArrayBuffer).
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (e) => e.waitUntil(self.clients.claim()));
self.addEventListener('fetch', (e) => {
  const req = e.request;
  // cross-origin requests (the model downloads) keep the browser's default handling
  if (new URL(req.url).origin !== self.location.origin) return;
  if (req.cache === 'only-if-cached' && req.mode !== 'same-origin') return;
  e.respondWith(
    fetch(req).then((res) => {
      if (res.status === 0) return res;
      const headers = new Headers(res.headers);
      headers.set('Cross-Origin-Opener-Policy', 'same-origin');
      // credentialless, not require-corp: cross-origin files load without cookies instead of being blocked
      headers.set('Cross-Origin-Embedder-Policy', 'credentialless');
      return new Response(res.body, { status: res.status, statusText: res.statusText, headers });
    }),
  );
});
